"""Generate a synthetic pack for scale tests (PRD NFR-3 / E7: at least 10 robots across 3 clusters).

    python scripts/make_scale_pack.py --wings 3 --robots 10 --out packs/scale10

Topology: a shared hub and a shared store; each wing has a gate, a hall and two wards (hub - gate - hall - wards, store - hall).
Items, rules, prompts and policies are copied from the hospital_sim pack, so the same code paths run. Wards are named w<k>a / w<k>b.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "packs" / "hospital_sim"


def build(wings: int, robots: int, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    pack = json.loads((SRC / "pack.json").read_text())
    pack["name"], pack["version"] = out.name, "0.1.0"
    pack["description"] = f"Synthetic scale pack: {wings} wings, {robots} robots (NFR-3 / E7). Generated by scripts/make_scale_pack.py."
    pack["locators"] = [{"type": "node", "label": "ward", "pattern": r"\b(w\d+[ab])\b", "id": "{g1}", "kinds": ["ward"]}]
    pack["restrictions"] = {k: v for k, v in pack["restrictions"].items()}
    nodes = {"hub": {"kind": "corridor", "area": "shared", "speed_cap": 0.45}, "store": {"kind": "store", "area": "shared", "speed_cap": 0.25, "label": "store"}}
    edges = []
    for w in range(wings):
        area = f"wing{w}"
        nodes[f"gate{w}"] = {"kind": "gate", "area": area, "exclusive": True, "speed_cap": 0.3}
        nodes[f"hall{w}"] = {"kind": "corridor", "area": area, "speed_cap": 0.4}
        for s in "ab":
            nodes[f"w{w}{s}"] = {"kind": "ward", "area": area, "beds": 20, "speed_cap": 0.3, "label": f"ward w{w}{s}"}
            edges.append([f"hall{w}", f"w{w}{s}", 4.0 + (s == "b") * 2])
        edges += [["hub", f"gate{w}", 5.0], [f"gate{w}", f"hall{w}", 4.0], ["store", f"hall{w}", 9.0 + w]]
    topo = {"version": f"scale-{wings}x", "note": "GENERATED by scripts/make_scale_pack.py", "nodes": nodes, "edges": edges,
            "clusters": {f"wing{w}-cluster": f"wing{w}" for w in range(wings)}}
    per = [robots // wings + (1 if i < robots % wings else 0) for i in range(wings)]
    fleet = {"note": "Generated seed fleet.", "clusters": {f"wing{w}-cluster": {
        "home": "store", "area": f"wing{w}", "robots": [f"r{w}{i}" for i in range(per[w])],
        "stock": {"wheelchair": 40, "iv_pole": 40, "monitor": 40, "blanket": 200, "infusion_pump": 40, "infusion_pump_paediatric": 20}}
        for w in range(wings)}}
    (out / "pack.json").write_text(json.dumps(pack, indent=1))
    (out / "topology.json").write_text(json.dumps(topo, indent=1))
    (out / "fleet.json").write_text(json.dumps(fleet, indent=1))
    for f in ("policies.json",):
        shutil.copy(SRC / f, out / f)
    shutil.copytree(SRC / "prompts", out / "prompts", dirs_exist_ok=True)
    (out / "scenarios.json").write_text("[]")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--wings", type=int, default=3)
    ap.add_argument("--robots", type=int, default=10)
    ap.add_argument("--out", default=str(ROOT / "packs" / "scale10"))
    a = ap.parse_args(argv)
    build(a.wings, a.robots, Path(a.out))
    print(f"wrote {a.out}: {a.wings} wings, {a.robots} robots")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
